-- =====================================================================
-- 01_raw.sql  (Extract + Load)
-- Copy source tables unchanged into RAW and stamp when they were loaded.
-- =====================================================================

USE ROLE SYSADMIN;
USE WAREHOUSE ELT_WH;
USE SCHEMA SALES_ANALYTICS.RAW;

CREATE OR REPLACE TABLE CUSTOMER AS
SELECT *, CURRENT_TIMESTAMP() AS _LOADED_AT
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER;

CREATE OR REPLACE TABLE ORDERS AS
SELECT *, CURRENT_TIMESTAMP() AS _LOADED_AT
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS;

CREATE OR REPLACE TABLE LINEITEM AS
SELECT *, CURRENT_TIMESTAMP() AS _LOADED_AT
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM;

CREATE OR REPLACE TABLE NATION AS
SELECT *, CURRENT_TIMESTAMP() AS _LOADED_AT
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION;

CREATE OR REPLACE TABLE REGION AS
SELECT *, CURRENT_TIMESTAMP() AS _LOADED_AT
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.REGION;

-- Quick look at volumes
SELECT 'CUSTOMER' AS table_name, COUNT(*) AS row_count FROM CUSTOMER
UNION ALL SELECT 'ORDERS',   COUNT(*) FROM ORDERS
UNION ALL SELECT 'LINEITEM', COUNT(*) FROM LINEITEM
UNION ALL SELECT 'NATION',   COUNT(*) FROM NATION
UNION ALL SELECT 'REGION',   COUNT(*) FROM REGION;
